export const DEMO_MAIN_ANSWER = `> **体验示例**：下面是预先准备的本地示例，用于试用划词批注。连接 API 后，你可以向自己的模型提问。

## 广义相对论是什么？

广义相对论是爱因斯坦在 1915 年建立的引力理论。它把引力描述为时空几何的表现：物质和能量影响时空的曲率，而自由运动的物体沿弯曲时空中的测地线前进。我们看到的下落和轨道运动，就与这种几何结构有关。

### 为什么说“时空弯曲”？

时空把空间与时间放在同一个四维框架中。所谓曲率，并不是必须把宇宙想成一块弯曲的橡皮膜，而是说距离、时间间隔和自由运动的路径，不再处处符合平直时空的关系。橡皮膜是帮助直觉的比喻，但会遗漏时间这一重要部分。

### 它会影响时间和光吗？

会。处在不同引力环境中的时钟，其走时速率可以不同。例如，在地球附近，位置较高的静止时钟相对较低的时钟走得稍快。光在弯曲时空中也沿相应的路径传播，因此会出现引力透镜等现象。这些效应已有实验和观测支持。

### 它与牛顿引力有什么关系？

在引力较弱、速度远低于光速等适当条件下，广义相对论给出的结果接近牛顿引力理论。牛顿理论仍然是许多日常和工程计算中很有效的近似；研究黑洞附近、精密计时或引力波时，则需要更完整的相对论描述。

试着选中 **“测地线”** 或 **“时钟走得稍快”**，点击出现的“批注提问”，就能在原处问一次问题。`;

