export function demoAnnotationAnswer(quote: string, question: string): string {
  let explanation = '在实际 API 模式中，模型会收到全部主对话、你选中的这段原文，以及这一次批注问题。其他批注的问答不会加入这次请求。';
  if (/测地线/.test(quote)) explanation = '测地线可以理解为时空几何所决定的“自然路径”。不受其他力推动的物体会沿这样的路径自由运动。在弯曲时空中，这条路径未必对应我们在空间里画出的直线。';
  else if (/时钟|时间|稍快/.test(quote)) explanation = '这里的“走得更快”是比较两只时钟后得到的物理差异，并非时钟故障。在地球附近，位置较高的静止时钟相对位置较低的时钟走得稍快；实际比较还要考虑运动等因素。';
  else if (/曲率|弯曲|橡皮膜/.test(quote)) explanation = '“弯曲”描述的是时空内部的几何关系，不要求时空嵌在一个更高维空间里。我们可以通过测量自由运动路径、光的传播或时钟的走时，检验这些几何关系。橡皮膜只是一种有限的比喻。';
  return `本地演示回答（未调用 AI）\n\n${explanation}\n\n你的问题：“${question}”\n\n这条批注已完成一次问答。你可以修改这里保存的文字；修改不会再次调用模型。`;
}
